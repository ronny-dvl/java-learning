package exercise_10;

public class DadosPessoais {
    private double altura;
    private String genero;

    public DadosPessoais(double altura, String genero) {
        this.altura = altura;
        this.genero = genero;
    }

    public double getAltura() {
        return altura;
    }

    public String getGenero() {
        return genero;
    }
}
