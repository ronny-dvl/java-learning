package exercise_09;

public class VectPessoaVelha {

    private String name;
    private int age;

    public VectPessoaVelha(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getName() {
        return name;
    }
}
